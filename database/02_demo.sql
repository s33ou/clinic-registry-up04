-- Слоты создаются на следующий день после первой установки.

INSERT INTO slots (id, doctor_id, starts_at)

SELECT (d.id - 1) * 3 + t.n, d.id, TIMESTAMP(CURDATE() + INTERVAL 1 DAY, t.hhmmss)

FROM doctors d CROSS JOIN (SELECT 1 AS n, '09:00:00' AS hhmmss UNION ALL SELECT 2, '09:20:00' UNION ALL SELECT 3, '09:40:00') t

WHERE d.id BETWEEN 1 AND 24 AND NOT EXISTS (SELECT 1 FROM (SELECT id FROM slots LIMIT 1) AS existing_slots);

INSERT INTO appointments (id, patient_id, slot_id)

SELECT patient.id, patient.id, (patient.id - 1) * 3 + 1 FROM patients patient

WHERE patient.id BETWEEN 1 AND 24 AND NOT EXISTS (SELECT 1 FROM (SELECT id FROM appointments LIMIT 1) AS existing_appointments);

INSERT INTO appointment_history (appointment_id, employee_id, action, new_slot_id)

SELECT a.id, 2, 'booked', a.slot_id FROM appointments a

WHERE a.id BETWEEN 1 AND 24 AND NOT EXISTS (SELECT 1 FROM (SELECT id FROM appointment_history LIMIT 1) AS existing_history);

